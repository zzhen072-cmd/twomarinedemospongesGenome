#!/usr/bin/env python3
"""Auditable GO generic-slim and KEGG pathway mappings (Python standard library).

No sample annotation or counts are generated by this module.  Run with --help
to export versioned reference tables, or import load_go and load_kegg.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import html
import json
import re
from collections import Counter, defaultdict
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterable, Optional

GO_ROOTS = frozenset({"GO:0008150", "GO:0003674", "GO:0005575"})
GO_ID = re.compile(r"GO:\d{7}\Z")
PATHWAY_ID = re.compile(r"(?:(?:path|pathway):)?(?:ko|map)?(\d{5})\Z", re.I)


@dataclass(frozen=True)
class GOTerm:
    id: str
    name: str
    namespace: str
    alt_ids: tuple[str, ...] = ()
    subsets: tuple[str, ...] = ()
    is_obsolete: bool = False
    replaced_by: tuple[str, ...] = ()
    consider: tuple[str, ...] = ()
    parents: tuple[tuple[str, str], ...] = ()


class GOOntology:
    """Parsed OBO ontology, with explicit identifier-resolution audit records."""

    def __init__(self, terms, header, source, subset="goslim_generic"):
        self.terms: dict[str, GOTerm] = terms
        self.header = header
        self.source = str(Path(source).resolve())
        self.subset = subset
        self.alt_ids: dict[str, str] = {}
        for term in terms.values():
            for alternate in term.alt_ids:
                if alternate in self.alt_ids and self.alt_ids[alternate] != term.id:
                    raise ValueError(f"Conflicting GO alternate identifier: {alternate}")
                if alternate in terms and alternate != term.id:
                    raise ValueError(f"GO alternate is also a primary identifier: {alternate}")
                self.alt_ids[alternate] = term.id
        self.slim_ids = frozenset(
            term.id for term in terms.values()
            if subset in term.subsets and not term.is_obsolete and term.id not in GO_ROOTS
        )
        if not self.slim_ids:
            raise ValueError(f"No active non-root terms in GO subset {subset!r}")
        self.resolution_log: dict[str, dict] = {}
        self._ancestor_cache: dict[str, frozenset[str]] = {}

    def canonicalize(self, go_id: str) -> dict:
        """Return input_id/canonical_id/status/chain/consider, recording resolution.

        Alternate IDs resolve to their primary term. An obsolete primary term is
        replaced only when it has exactly one distinct replaced_by target; chains
        are followed. 'consider' is recorded but never used as a replacement.
        Returned chain is a tuple of visited IDs; None means unresolved.
        """
        original = str(go_id).strip()
        if original in self.resolution_log:
            return dict(self.resolution_log[original])
        current = original
        chain = []
        operations = []
        suggestions = set()
        canonical = None
        while True:
            if not GO_ID.fullmatch(current):
                status = "invalid_id"
                break
            if current in chain:
                chain.append(current)
                status = "resolution_cycle"
                break
            chain.append(current)
            if current in self.alt_ids:
                operations.append("alt_id")
                current = self.alt_ids[current]
                continue
            term = self.terms.get(current)
            if term is None:
                status = "unknown_id"
                break
            if not term.is_obsolete:
                canonical = current
                status = "+".join(dict.fromkeys(operations)) if operations else "exact"
                break
            suggestions.update(term.consider)
            replacements = set(term.replaced_by)
            if len(replacements) != 1:
                status = "obsolete_ambiguous" if replacements else "obsolete_unresolved"
                break
            operations.append("replaced_by")
            current = next(iter(replacements))
        result = {
            "input_id": original, "canonical_id": canonical, "status": status,
            "chain": tuple(chain), "consider": tuple(sorted(suggestions)),
        }
        self.resolution_log[original] = result
        return dict(result)

    def resolve(self, go_id: str) -> Optional[str]:
        """Return an active primary ID, or None when unresolved."""
        return self.canonicalize(go_id)["canonical_id"]

    def ancestors(self, go_id: str) -> frozenset[str]:
        """Active ancestors via is_a/part_of, including the canonical term itself.

        Other relations, such as regulates and has_part, are deliberately omitted.
        Traversal does not restrict namespace; target slim term namespace is used.
        """
        canonical = self.resolve(go_id)
        if canonical is None:
            return frozenset()
        if canonical in self._ancestor_cache:
            return self._ancestor_cache[canonical]
        seen = set()
        pending = [canonical]
        while pending:
            current = pending.pop()
            if current in seen:
                continue
            seen.add(current)
            cached = self._ancestor_cache.get(current)
            if cached is not None:
                seen.update(cached)
                continue
            for relation, parent in self.terms[current].parents:
                if relation in {"is_a", "part_of"}:
                    resolved_parent = self.resolve(parent)
                    if resolved_parent and resolved_parent not in seen:
                        pending.append(resolved_parent)
        result = frozenset(seen)
        self._ancestor_cache[canonical] = result
        return result

    def slim_for(self, go_id: str) -> frozenset[str]:
        """All matching generic-slim ancestors, including self and excluding roots."""
        return self.ancestors(go_id) & self.slim_ids

    def map_terms(self, go_ids: Iterable[str]) -> frozenset[str]:
        """Deduplicated union for one gene's GO IDs; count each gene once per bin."""
        result = set()
        for go_id in go_ids:
            result.update(self.slim_for(go_id))
        return frozenset(result)

    def mapping(self, go_id: str) -> dict:
        """Full resolution plus canonical name/namespace and all slim IDs."""
        record = self.canonicalize(go_id)
        term = self.terms.get(record["canonical_id"])
        record.update({
            "name": term.name if term else "",
            "namespace": term.namespace if term else "",
            "slim_ids": tuple(sorted(self.slim_for(go_id))),
        })
        return record


def load_go(path, subset="goslim_generic") -> GOOntology:
    """Read the OBO [Term] stanzas; retain is_a and named relation edges."""
    terms = {}
    header = defaultdict(list)
    stanza = None
    fields = defaultdict(list)

    def flush():
        if stanza != "Term" or not fields.get("id"):
            return
        identifier = fields["id"][0]
        parents = [("is_a", value.split()[0]) for value in fields["is_a"]]
        for value in fields["relationship"]:
            tokens = value.split()
            if len(tokens) >= 2:
                parents.append((tokens[0], tokens[1]))
        if identifier in terms:
            raise ValueError(f"Duplicate GO term: {identifier}")
        terms[identifier] = GOTerm(
            id=identifier,
            name=fields.get("name", [""])[0],
            namespace=fields.get("namespace", [""])[0],
            alt_ids=tuple(fields["alt_id"]),
            subsets=tuple(fields["subset"]),
            is_obsolete=fields.get("is_obsolete", ["false"])[0] == "true",
            replaced_by=tuple(value.split()[0] for value in fields["replaced_by"]),
            consider=tuple(value.split()[0] for value in fields["consider"]),
            parents=tuple(parents),
        )

    with Path(path).open(encoding="utf-8") as handle:
        for raw in handle:
            line = raw.strip()
            if not line or line.startswith("!"):
                continue
            if line.startswith("[") and line.endswith("]"):
                flush()
                stanza = line[1:-1]
                fields = defaultdict(list)
                continue
            if ": " in line:
                key, value = line.split(": ", 1)
                (header if stanza is None else fields)[key].append(value)
        flush()
    return GOOntology(terms, dict(header), path, subset)


def normalize_pathway(pathway_id: str) -> Optional[str]:
    """Normalize koNNNNN/mapNNNNN/NNNNN and optional path: prefix to mapNNNNN.

    Invalid/organism-specific IDs return None. Existence is checked separately in
    KEGGHierarchy.pathways. This does not equate K numbers with pathway IDs.
    """
    match = PATHWAY_ID.fullmatch(str(pathway_id).strip())
    return f"map{match.group(1)}" if match else None


class KEGGHierarchy:
    """All pathway memberships; one pathway may appear under multiple L2 bins."""

    normalize_pathway = staticmethod(normalize_pathway)

    def __init__(self, records, ko_to_pathways, source, non_pathway_c):
        self.source = str(Path(source).resolve())
        self.records = tuple(sorted(records, key=lambda row: (
            row["A_id"], row["B_id"], row["pathway_id"])))
        grouped = defaultdict(list)
        for record in self.records:
            grouped[record["pathway_id"]].append(record)
        self.pathways = {key: tuple(value) for key, value in grouped.items()}
        self.ko_to_pathways = {key: frozenset(value) for key, value in ko_to_pathways.items()}
        self.non_pathway_c_records = non_pathway_c

    def hierarchy_for(self, pathway_ids: Iterable[str]) -> tuple[dict, ...]:
        """Return every distinct pathway/A/B row for normalized input IDs."""
        normalized = {normalize_pathway(value) for value in pathway_ids}
        return tuple(row for row in self.records if row["pathway_id"] in normalized)

    def pathways_for_kos(self, ko_ids: Iterable[str]) -> frozenset[str]:
        """Union pathway IDs inferred from supplied KO IDs in this local hierarchy."""
        result = set()
        for identifier in ko_ids:
            key = str(identifier).strip().removeprefix("ko:")
            result.update(self.ko_to_pathways.get(key, ()))
        return frozenset(result)


def load_kegg(path) -> KEGGHierarchy:
    """Read ko00001.keg, retaining only C entries explicitly marked [PATH:...].

    [BR:...] protein family and unclassified C entries are not pathway records.
    D-level KO associations are collected only under eligible pathway entries.
    """
    a_id = a_name = b_id = b_name = ""
    current_pathways = set()
    records = {}
    ko_to_pathways = defaultdict(set)
    non_pathway_c = 0
    with Path(path).open(encoding="utf-8") as handle:
        for raw in handle:
            line = html.unescape(re.sub(r"<[^>]*>", "", raw.rstrip()))
            match = re.match(r"^([ABC])\s*(\d{5})\s+(.+)$", line)
            if match:
                level, identifier, description = match.groups()
                if level == "A":
                    a_id, a_name = identifier, description
                    b_id = b_name = ""
                    current_pathways = set()
                elif level == "B":
                    b_id, b_name = identifier, description
                    current_pathways = set()
                else:
                    current_pathways = set()
                    tags = re.findall(r"\[PATH:([^\]]+)\]", description)
                    for tag in tags:
                        for token in tag.split():
                            normalized = normalize_pathway(token)
                            if normalized is None:
                                raise ValueError(f"Unsupported pathway ID: {token}")
                            current_pathways.add(normalized)
                    if not current_pathways:
                        non_pathway_c += 1
                    pathway_name = re.sub(r"\s*\[PATH:[^\]]+\]", "", description).strip()
                    for normalized in current_pathways:
                        if not a_id or not b_id:
                            raise ValueError(f"Pathway lacks A/B context: {line}")
                        row = {
                            "pathway_id": normalized, "pathway_name": pathway_name,
                            "A_id": a_id, "A_name": a_name, "B_id": b_id, "B_name": b_name,
                        }
                        key = (normalized, a_id, b_id)
                        if key in records and records[key] != row:
                            raise ValueError(f"Conflicting KEGG hierarchy row: {key}")
                        records[key] = row
            elif line.startswith("D") and current_pathways:
                ko_match = re.match(r"^D\s+(K\d{5})(?:\s|$)", line)
                if ko_match:
                    ko_to_pathways[ko_match.group(1)].update(current_pathways)
    if not records:
        raise ValueError(f"No KEGG [PATH:...] entries found in {path}")
    return KEGGHierarchy(list(records.values()), ko_to_pathways, path, non_pathway_c)


def sha256_file(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _write_tsv(path, columns, rows):
    with Path(path).open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns, delimiter="\t", lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def export_reference(go_path, kegg_path, output_dir):
    """Export reference tables and provenance; counts are ontology entries only."""
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)
    go = load_go(go_path)
    kegg = load_kegg(kegg_path)
    _write_tsv(out / "goslim_generic_terms.tsv", ["go_id", "name", "namespace"], (
        {"go_id": identifier, "name": go.terms[identifier].name,
         "namespace": go.terms[identifier].namespace}
        for identifier in sorted(go.slim_ids, key=lambda key: (go.terms[key].namespace, key))
    ))
    status_counts = Counter()

    def mapping_rows():
        for identifier in sorted(set(go.terms) | set(go.alt_ids)):
            row = go.mapping(identifier)
            status_counts[row["status"]] += 1
            yield {
                "input_id": identifier, "canonical_id": row["canonical_id"] or "",
                "status": row["status"], "resolution_chain": ";".join(row["chain"]),
                "consider": ";".join(row["consider"]), "canonical_name": row["name"],
                "canonical_namespace": row["namespace"],
                "slim_ids": ";".join(row["slim_ids"]),
                "slim_names": ";".join(go.terms[key].name for key in row["slim_ids"]),
                "slim_namespaces": ";".join(go.terms[key].namespace for key in row["slim_ids"]),
            }

    _write_tsv(out / "go_to_goslim_generic.tsv", [
        "input_id", "canonical_id", "status", "resolution_chain", "consider", "canonical_name",
        "canonical_namespace", "slim_ids", "slim_names", "slim_namespaces",
    ], mapping_rows())
    _write_tsv(out / "kegg_pathway_hierarchy.tsv", [
        "pathway_id", "pathway_name", "A_id", "A_name", "B_id", "B_name",
    ], kegg.records)
    _write_tsv(out / "kegg_ko_to_pathway.tsv", ["ko_id", "pathway_id"], (
        {"ko_id": ko_id, "pathway_id": pathway}
        for ko_id in sorted(kegg.ko_to_pathways)
        for pathway in sorted(kegg.ko_to_pathways[ko_id])
    ))
    source_provenance = {
        "GO ontology": {
            "source_url": "https://current.geneontology.org/ontology/go-basic.obo",
            "acquired_local_date": "2026-09-14",
            "acquisition_command": "curl -L https://current.geneontology.org/ontology/go-basic.obo -o go-basic.obo",
            "license_note": "GO data are distributed under CC BY 4.0; retain source and attribution when redistributing.",
        },
        "KEGG KO hierarchy": {
            "source_url": "https://rest.kegg.jp/get/br:ko00001",
            "acquired_local_date": "2026-09-14",
            "acquisition_command": "curl -L https://rest.kegg.jp/get/br:ko00001 -o ko00001.keg",
            "redistribution_note": "No release header is present. Recheck current KEGG terms before redistributing the raw file; derived mappings retain URL, date and checksum.",
        },
    }
    source_records = []
    for source, kind in [(go_path, "GO ontology"), (kegg_path, "KEGG KO hierarchy")]:
        path = Path(source).resolve()
        source_records.append({
            "kind": kind, "path": str(path), "bytes": path.stat().st_size,
            "sha256": sha256_file(path),
            "file_mtime_utc": datetime.fromtimestamp(path.stat().st_mtime, timezone.utc).isoformat(),
            "release": go.header.get("data-version", [None])[0] if kind == "GO ontology" else None,
            **source_provenance[kind],
        })
    documented_outputs = sorted(out.glob("*.tsv"))
    documented_outputs.extend(path for path in (out / "README.md", out / "mapping_validation.json") if path.exists())
    manifest = {
        "generated_utc": datetime.now(timezone.utc).isoformat(),
        "description": "Reference ontology entries only; no sample/gene annotation counts.",
        "sources": source_records,
        "go_mapping": {
            "subset": go.subset, "relations": ["is_a", "part_of"],
            "selection": "all matching ancestors including self; three roots excluded",
            "excluded_roots": sorted(GO_ROOTS),
            "obsolete_policy": "follow only single distinct replaced_by; never consider",
            "namespace_policy": "traverse valid relations across namespaces; assign target namespace",
            "primary_terms": len(go.terms), "alternative_ids": len(go.alt_ids),
            "slim_terms": len(go.slim_ids),
            "slim_terms_by_namespace": dict(Counter(go.terms[key].namespace for key in go.slim_ids)),
            "reference_resolution_status_counts": dict(sorted(status_counts.items())),
        },
        "kegg_mapping": {
            "normal_form": "mapNNNNN", "eligible_C_nodes": "explicit [PATH:...] only",
            "membership_key": ["pathway_id", "A_id", "B_id"],
            "unique_pathways": len(kegg.pathways), "hierarchy_rows": len(kegg.records),
            "pathways_in_multiple_L2": sum(len(rows) > 1 for rows in kegg.pathways.values()),
            "KO_ids_with_pathways": len(kegg.ko_to_pathways),
            "excluded_non_pathway_C_records": kegg.non_pathway_c_records,
            "release_note": "Local file has no release header; modification time is not release date.",
        },
        "module_sha256": sha256_file(__file__),
        "outputs": {path.name: {"sha256": sha256_file(path), "bytes": path.stat().st_size}
                    for path in documented_outputs},
    }
    (out / "reference_manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return manifest


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--go", required=True, help="Local go-basic.obo")
    parser.add_argument("--kegg", required=True, help="Local ko00001.keg")
    parser.add_argument("--out", required=True, help="Output reference directory")
    arguments = parser.parse_args()
    result = export_reference(arguments.go, arguments.kegg, arguments.out)
    print(json.dumps({"go_mapping": result["go_mapping"], "kegg_mapping": result["kegg_mapping"]}, indent=2))
